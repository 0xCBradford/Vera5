export function scoringBasis(
  code: ScoringBasisCode,
  value?: string | number | boolean,
  sourceField?: string
): { code: string; label: string; value?: string | number | boolean; sourceField?: string } {
  return {
    code,
    label: SCORING_BASIS_LABEL[code],
    ...(value === undefined ? {} : { value }),
    ...(sourceField === undefined ? {} : { sourceField }),
  };
}
